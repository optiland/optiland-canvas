"""Write the canvas's built-in film catalogue from the refractiveindex.info database.

    python tools/ri_import.py [--db <data-nk directory>]

Offline: it reads the database as Optiland packages it (``optiland/database/
data-nk``, found through the installed ``optiland`` unless ``--db`` names
another copy), never the network, and writes
``crates/oc-core/src/film_catalog_data.rs``. Re-running it on the same database
writes the same file.

The database is CC0 (M. N. Polyanskiy, refractiveindex.info). Every entry
keeps the paper it cites, its page, its wavelength range, and whether it is a
thin film, a bulk sample or a crystal: a film's index differs from the bulk by
a few percent and by process, and the catalogue says which one it is.

Tables are cut to 0.25 to 2.6 um (the visible and the solar spectrum, which is what the canvas traces), keeping the knot on each side of the cut so
that every wavelength in that range interpolates between the source's own
knots. The values are written as the source prints them, so each knot
reproduces the source exactly.
"""

from __future__ import annotations

import argparse
import html
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates" / "oc-core" / "src" / "film_catalog_data.rs"
CUT_UM = (0.25, 2.6)
NOMINAL_UM = 0.55

# key, display name, database path (shelf/book/page), form, note
ENTRIES = [
    ("magnesium_fluoride", "MgF2 (film)", "main/MgF2/Rodriguez-de Marcos", "Film", ""),
    ("silica", "SiO2 (film)", "main/SiO2/Lemarchand", "Film", ""),
    ("alumina", "Al2O3 (film)", "main/Al2O3/Boidin", "Film", "k not measured; zero"),
    ("titania", "TiO2 (film)", "main/TiO2/Siefke", "Film", ""),
    ("tantala", "Ta2O5 (film)", "main/Ta2O5/Gao", "Film", ""),
    ("hafnia", "HfO2 (film)", "main/HfO2/Al-Kuhaili", "Film", "k not given; zero"),
    (
        "zirconia",
        "ZrO2-Y2O3 (crystal)",
        "other/mixed crystals/ZrO2-Y2O3/Wood",
        "Crystal",
        "yttria-stabilized cubic zirconia, bulk crystal: the database has no ZrO2 film data; k zero",
    ),
    ("niobia", "Nb2O5 (film)", "main/Nb2O5/Lemarchand", "Film", ""),
    ("zinc_sulfide", "ZnS (film)", "main/ZnS/Amotchkina", "Film", "k tabulated 0.4 to 1.0 um, held at its end values outside"),
    ("silicon", "Si", "main/Si/Green-2008", "Bulk", ""),
    ("silver", "Ag", "main/Ag/Babar", "Film", ""),
    ("silver_johnson", "Ag (Johnson and Christy)", "main/Ag/Johnson", "Film", ""),
    ("aluminium", "Al", "main/Al/Rakic", "Film", ""),
    ("gold", "Au", "main/Au/Johnson", "Film", ""),
    ("chromium", "Cr", "main/Cr/Johnson", "Film", ""),
    ("nickel", "Ni", "main/Ni/Johnson", "Film", ""),
]


def default_db() -> Path:
    import optiland

    return Path(optiland.__file__).resolve().parent / "database" / "data-nk"


def clean(text: str) -> str:
    text = re.sub(r"<[^>]+>", "", str(text))
    return " ".join(html.unescape(text).split())


def rows_of(block: dict) -> list[list[str]]:
    return [r.split() for r in block["data"].strip().splitlines()]


def cut(rows: list[list[str]]) -> list[list[str]]:
    """Rows inside CUT_UM, and the knot on either side of it."""
    lam = [float(r[0]) for r in rows]
    lo = max([i for i, x in enumerate(lam) if x <= CUT_UM[0]] or [0])
    hi = min([i for i, x in enumerate(lam) if x >= CUT_UM[1]] or [len(lam) - 1])
    return rows[lo : hi + 1]


def interp(rows: list[list[str]], col: int, x: float) -> float:
    lam = [float(r[0]) for r in rows]
    ys = [float(r[col]) for r in rows]
    if x <= lam[0]:
        return ys[0]
    if x >= lam[-1]:
        return ys[-1]
    for i in range(len(lam) - 1):
        if lam[i] <= x <= lam[i + 1]:
            f = (x - lam[i]) / (lam[i + 1] - lam[i])
            return ys[i] + f * (ys[i + 1] - ys[i])
    raise AssertionError


def formula_n(kind: int, c: list[float], x: float) -> float:
    l2 = x * x
    if kind == 1:
        n2 = 1 + c[0]
        for i in range(1, len(c), 2):
            n2 += c[i] * l2 / (l2 - c[i + 1] ** 2)
        return n2**0.5
    if kind == 2:
        n2 = 1 + c[0]
        for i in range(1, len(c), 2):
            n2 += c[i] * l2 / (l2 - c[i + 1])
        return n2**0.5
    if kind == 5:
        n = c[0]
        for i in range(1, len(c), 2):
            n += c[i] * x ** c[i + 1]
        return n
    raise ValueError(f"formula {kind} is not one the catalogue needs")


def rust_f(s: str) -> str:
    """A source number as a Rust f64 literal, digits unchanged."""
    v = s.strip()
    if re.fullmatch(r"[-+]?\d+", v):
        return v + ".0"
    if v.startswith("."):
        return "0" + v
    if v.startswith("-."):
        return "-0" + v[1:]
    return v


def emit(db: Path) -> str:
    out = [
        "// @generated by tools/ri_import.py from the refractiveindex.info database",
        "// (CC0, M. N. Polyanskiy) as Optiland packages it. Do not edit; re-run the script.",
        "",
        "// Measured values, written with the source's digits: a 3.14 here is an index, not pi.",
        "#![allow(clippy::approx_constant, clippy::excessive_precision)]",
        "",
        "use super::{Data, Entry};",
        "use crate::thinfilm::FilmForm;",
        "",
        "pub(crate) const ENTRIES: &[Entry] = &[",
    ]
    for key, name, page, form, note in ENTRIES:
        doc = yaml.safe_load(open(db / f"{page}.yml", encoding="utf-8"))
        reference = clean(doc.get("REFERENCES", ""))
        comment = clean(doc.get("COMMENTS", ""))
        blocks = doc["DATA"]
        shelf, book, pg = page.split("/", 2) if page.count("/") == 2 else (page.split("/")[0], "/".join(page.split("/")[1:-1]), page.split("/")[-1])
        url = "https://refractiveindex.info/?shelf={}&book={}&page={}".format(
            shelf, book.replace(" ", "%20"), pg.replace(" ", "%20")
        )
        first = blocks[0]
        if first["type"] == "tabulated nk":
            rows = cut(rows_of(first))
            lo, hi = float(rows[0][0]), float(rows[-1][0])
            nominal = (interp(rows, 1, NOMINAL_UM), interp(rows, 2, NOMINAL_UM))
            body = ",\n".join(f"        [{rust_f(a)}, {rust_f(b)}, {rust_f(c)}]" for a, b, c in rows)
            data = f"Data::TableNk(&[\n{body},\n    ])"
        elif first["type"] == "tabulated n":
            rows = cut(rows_of(first))
            lo, hi = float(rows[0][0]), float(rows[-1][0])
            nominal = (interp(rows, 1, NOMINAL_UM), 0.0)
            body = ",\n".join(f"        [{rust_f(a)}, {rust_f(b)}]" for a, b in rows)
            data = f"Data::TableN(&[\n{body},\n    ])"
        elif first["type"].startswith("formula"):
            kind = int(first["type"].split()[1])
            coeffs = first["coefficients"].split() if isinstance(first["coefficients"], str) else [str(x) for x in first["coefficients"]]
            lo, hi = (float(x) for x in str(first["wavelength_range"]).split())
            c = [float(x) for x in coeffs]
            k_rows = None
            for b in blocks[1:]:
                if b["type"] == "tabulated k":
                    k_rows = rows_of(b)
            nominal = (formula_n(kind, c, NOMINAL_UM), interp(k_rows, 1, NOMINAL_UM) if k_rows else 0.0)
            cs = ", ".join(rust_f(x) for x in coeffs)
            if k_rows:
                kb = ",\n".join(f"            [{rust_f(a)}, {rust_f(b)}]" for a, b in k_rows)
                kpart = f"Some(&[\n{kb},\n        ])"
            else:
                kpart = "None"
            data = f"Data::Formula {{\n        formula: {kind},\n        coefficients: &[{cs}],\n        k: {kpart},\n    }}"
        else:
            raise ValueError(f"{page}: {first['type']}")
        out.append("    Entry {")
        out.append(f'        key: "{key}",')
        out.append(f'        name: "{name}",')
        out.append(f"        form: FilmForm::{form},")
        out.append(f"        reference: {rust_str(reference)},")
        out.append(f"        url: {rust_str(url)},")
        out.append(f"        note: {rust_str('; '.join(x for x in (comment, note) if x))},")
        out.append(f"        range_um: [{lo!r}, {hi!r}],")
        out.append(f"        nominal: [{nominal[0]!r}, {nominal[1]!r}],")
        out.append(f"        data: {data},")
        out.append("    },")
    out.append("];")
    return "\n".join(out) + "\n"


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--db", type=Path, default=None, help="the database's data-nk directory")
    args = ap.parse_args()
    db = args.db or default_db()
    OUT.write_text(emit(db), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} from {db}")


if __name__ == "__main__":
    main()
