//! What the eye makes of light: the CIE 1931 standard observer.
//!
//! A detector that should show what a person would see weighs each ray by the
//! three colour-matching functions `x̄, ȳ, z̄` at its wavelength. `ȳ` is the
//! photopic luminous efficiency `V(λ)`, so `683 lm/W · Σ Φ ȳ` over an area is
//! the illuminance a light meter reads, and the `(X, Y, Z)` triple is the
//! colour. The picture is then that triple on an sRGB display.
//!
//! The table is the CIE 1931 2° observer at 5 nm from 360 to 830 nm, taken
//! from the 1 nm table the Colour & Vision Research Laboratory (UCL) publishes
//! (`ciexyz31_1.csv`), every fifth row. Between rows it is linear, and outside
//! them zero.

/// Lumens per watt at the peak of `V(λ)`, 555 nm (the SI definition of the
/// candela fixes 683 lm/W at 540 THz; 683.002 is the value at 555 nm in air).
pub const LM_PER_W: f64 = 683.002;

const FIRST_NM: f64 = 360.0;
const STEP_NM: f64 = 5.0;

