// The 3D-preview (Scene3 slice) browser test (§19.5, PR 3D-09).
//
// What only a browser can show: that opening an `.ocanvas` into the canonical 3D
// scene wires all the way through — the file reaches `loadScene3JSON`, the badge
// reflects `previewMode`, and the authoritative f64 paths from `traceProjected3D`
// actually paint onto the view. It asserts through the page's own panels and
// pixels, so it fails if the *page* stops working, not merely if a binding does.
//
// The Rust side proves the physics and the API headlessly (oc-wasm `scene3_tests`
// and the oc-gpu parity suites). This is the seam between them and the DOM.

import { test, expect } from "@playwright/test";

// The demo fixture is generated by the ignored oc-wasm test `write_demo_3d_fixture`
// and served from web/public. Paths are resolved against the Playwright cwd (web/).
const FIXTURE = "public/demo-3d.ocanvas";

test.describe("3D preview — the 2D Canvas as a slice of Scene3", () => {
  test("opens a v2 scene, flips the badge to full-3D, and paints projected rays", async ({
    page,
  }) => {
    await page.goto("/");
    // Wait until the app is live (the HUD reports a trace), so the slice3d
    // listeners are attached before we drive the file input.
    await expect(page.locator("#stat")).toContainText("segs");

    const badge = page.locator("#preview3dBadge");
    await expect(badge).toHaveText("no 3D scene");
    await expect(page.locator("#slice3dRow")).toBeHidden();

    // Open the demo scene into the canonical 3D scene (a native v2 glass sphere).
    await page.locator("#open3dFile").setInputFiles(FIXTURE);

    // The badge never lies: a real 3D body ⇒ full-3D projected, not legacy planar.
    await expect(badge).toHaveClass(/full_3d/);
    await expect(badge).toContainText("full 3D");
    await expect(page.locator("#preview3dMsg")).toContainText("dimension 3");
    await expect(page.locator("#slice3dRow")).toBeVisible();

    // The projected f64 paths actually render: the dark background gains lit
    // pixels once the rays are drawn.
    const lit = await litPixels(page);
    expect(lit).toBeGreaterThan(200);
  });

  test("the slice-thickness filter thins the projection", async ({ page }) => {
    await page.goto("/");
    await expect(page.locator("#stat")).toContainText("segs");
    await page.locator("#open3dFile").setInputFiles(FIXTURE);
    await expect(page.locator("#preview3dBadge")).toHaveClass(/full_3d/);

    // Everything projected (slider at 0 ⇒ ∞).
    const wide = await litPixels(page);
    expect(wide).toBeGreaterThan(200);

    // A razor-thin slice keeps only paths that come within it of the plane, so
    // fewer pixels are lit than with no filter.
    const slider = page.locator("#slice3d");
    await slider.fill("0.5");
    await slider.dispatchEvent("input");
    await expect(page.locator("#slice3dLabel")).toHaveText("0.5");
    const thin = await litPixels(page);
    expect(thin).toBeLessThanOrEqual(wide);
  });
});

/// Count perceptibly-lit pixels on the main view canvas (background is near-black).
async function litPixels(page: import("@playwright/test").Page): Promise<number> {
  return page.evaluate(() => {
    const c = document.getElementById("view") as HTMLCanvasElement;
    const ctx = c.getContext("2d")!;
    const { data } = ctx.getImageData(0, 0, c.width, c.height);
    let n = 0;
    for (let i = 0; i < data.length; i += 4) {
      if (data[i] + data[i + 1] + data[i + 2] > 60) n++;
    }
    return n;
  });
}
