/// The CIE 1931 2° colour-matching functions `[x̄, ȳ, z̄]` at a wavelength in
/// micrometres: zero outside 360 to 830 nm.
pub fn cie_1931(lambda_um: f64) -> [f64; 3] {
    let t = (lambda_um * 1e3 - FIRST_NM) / STEP_NM;
    if !(0.0..=(CMF_1931.len() - 1) as f64).contains(&t) {
        return [0.0; 3];
    }
    let i = (t.floor() as usize).min(CMF_1931.len() - 2);
    let f = t - i as f64;
    let (a, b) = (CMF_1931[i], CMF_1931[i + 1]);
    [
        a[0] + f * (b[0] - a[0]),
        a[1] + f * (b[1] - a[1]),
        a[2] + f * (b[2] - a[2]),
    ]
}

/// `(X, Y, Z)` to linear sRGB (D65 white, IEC 61966-2-1). The result can be
/// negative: a spectral colour lies outside what three sRGB primaries mix,
/// and what to do about that is the display's choice, not the physics'.
pub fn xyz_to_linear_srgb(xyz: [f64; 3]) -> [f64; 3] {
    let [x, y, z] = xyz;
    [
        3.240_454_2 * x - 1.537_138_5 * y - 0.498_531_4 * z,
        -0.969_266_0 * x + 1.876_010_8 * y + 0.041_556_0 * z,
        0.055_643_4 * x - 0.204_025_9 * y + 1.057_225_2 * z,
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_observer_peaks_at_555_nm_and_vanishes_outside_its_range() {
        assert_eq!(cie_1931(0.555)[1], 1.0);
        assert_eq!(cie_1931(0.350), [0.0; 3]);
        assert_eq!(cie_1931(0.900), [0.0; 3]);
        // Halfway between rows is the mean of the two.
        let (a, b, m) = (cie_1931(0.550), cie_1931(0.555), cie_1931(0.5525));
        assert!((m[1] - 0.5 * (a[1] + b[1])).abs() < 1e-15);
    }

    #[test]
    fn equal_energy_light_has_equal_tristimulus_values() {
        // Illuminant E is defined by X = Y = Z; the 5 nm table integrates to
        // 106.86 per channel to within a tenth of a percent.
        let mut s = [0.0; 3];
        for row in CMF_1931 {
            for k in 0..3 {
                s[k] += row[k] * STEP_NM;
            }
        }
        for k in 0..3 {
            assert!((s[k] / 106.857 - 1.0).abs() < 1e-3, "{s:?}");
        }
    }

    #[test]
    fn d65_white_is_srgb_white() {
        let rgb = xyz_to_linear_srgb([0.950_47, 1.0, 1.088_83]);
        for c in rgb {
            assert!((c - 1.0).abs() < 1e-3, "{rgb:?}");
        }
        // Sodium yellow lies outside the sRGB gamut: its blue goes negative.
        assert!(xyz_to_linear_srgb(cie_1931(0.589))[2] < 0.0);
    }
}
