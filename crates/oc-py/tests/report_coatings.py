"""Write the coating validation report (coating-fidelity spec CF-12, C32).

Runs the oracle matrix, every frozen fixture in ``data/coatings`` against
every oracle it holds (Byrnes ``tmm``, Optiland ``thin_film``), through the
same comparison the fixture test applies, and writes one table: case, oracle,
quantity, tolerance, worst error, profile. The commit the report was made at
heads the file.

Worst errors are written rounded up to a power of ten ("<= 1e-15"): the
digits below that are floating-point noise that differs between machines.
``--check`` compares everything but that column and the commit line, so the
report regenerates with no difference on a clean checkout of any platform.

    python tests/report_coatings.py            # writes docs/validation-coatings.md
    python tests/report_coatings.py --check    # fails if the file is stale
    python tests/report_coatings.py --out PATH # writes elsewhere (the CI artifact)

Rows computed under different fidelity profiles never share a table without a
profile column: :func:`render` refuses (spec rule 4, C34).
"""

from __future__ import annotations

import argparse
import json
import math
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from coating_compare import TOLERANCES, worst  # noqa: E402

ROOT = HERE.parents[2]
DEFAULT_OUT = ROOT / "docs" / "validation-coatings.md"
FIXTURES = HERE / "data" / "coatings"

# The profile the fixtures are evaluated under: `coatings.rt` and
# `coatings.amplitudes` run the solver with the default context, which is
# Standard's (dispersive materials, permissive numerics, no temperature).
PROFILE = "Standard"


@dataclass(frozen=True)
class Row:
    case: str
    cid: str
    oracle: str
    quantity: str
    tolerance: float
    worst: float
    profile: str

    @property
    def passes(self) -> bool:
        return self.worst <= self.tolerance


def ceil_pow10(x: float) -> str:
    """`x` rounded up to a power of ten, as a person reads a bound."""
    if x == 0.0:
        return "0"
    return f"<= 1e{math.ceil(math.log10(x)):d}"


def rows() -> list[Row]:
    out = []
    for path in sorted(FIXTURES.glob("*.json")):
        if path.name == "tolerances.json":
            continue
        doc = json.loads(path.read_text())
        desc = doc.get("description", "")
        cid = desc.split(":")[0] if desc.startswith("C") and ":" in desc[:5] else "-"
        for oracle in sorted(doc["oracles"]):
            for quantity, (d, _) in worst(doc, oracle).items():
                out.append(Row(doc["case"], cid, oracle, quantity, TOLERANCES[oracle][quantity], d, PROFILE))
    return out


def commit() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short=9", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def render(rs: list[Row], at: str, profile_column: bool = True) -> str:
    """The report as markdown. Without a profile column every row must share
    one profile, or the table would quietly mix two kinds of number."""
    profiles = {r.profile for r in rs}
    if not profile_column and len(profiles) > 1:
        raise ValueError(
            f"rows computed under {sorted(profiles)} cannot share a table without a profile column"
        )
    head = ["case", "C", "oracle", "quantity", "tolerance", "worst", "profile"]
    if not profile_column:
        head.remove("profile")
    lines = [
        "# Coating validation report",
        "",
        f"Generated by `crates/oc-py/tests/report_coatings.py` at commit `{at}`. Do not edit by hand.",
        "",
        "Every frozen case in `crates/oc-py/tests/data/coatings` against every oracle it holds, through the "
        "comparison `test_coating_fixtures.py` applies: absolute error on the s and p powers and on the complex "
        "amplitudes in the kernel's ray frame. Optiland is compared below the critical angle only (spec section 9). "
        "Worst errors are rounded up to a power of ten.",
        "",
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
    ]
    for r in rs:
        cells = [r.case, r.cid, r.oracle, r.quantity, f"{r.tolerance:.0e}", ceil_pow10(r.worst)]
        if profile_column:
            cells.append(r.profile)
        lines.append("| " + " | ".join(cells) + " |")
    failed = [r for r in rs if not r.passes]
    lines += ["", f"{len(rs)} comparisons, {len(failed)} over tolerance.", ""]
    return "\n".join(lines)


def comparable(text: str) -> str:
    """The report without what may differ between two machines at one commit:
    the commit line, and the worst-error column (a value near a power of ten
    can round to either side of it). Cases, oracles, tolerances, profiles and
    the pass count must match."""
    out = []
    for line in text.splitlines():
        if line.startswith("Generated by "):
            continue
        if line.startswith("| ") and not line.startswith("| case"):
            cells = line.split(" | ")
            cells[5] = "-"
            line = " | ".join(cells)
        out.append(line)
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed report is stale")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    rs = rows()
    text = render(rs, commit())
    bad = [r for r in rs if not r.passes]
    if args.check:
        old = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if comparable(old) != comparable(text):
            print(f"{args.out} is stale: run tests/report_coatings.py", file=sys.stderr)
            return 1
        print("report up to date")
    else:
        args.out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {args.out} ({len(rs)} comparisons)")
    for r in bad:
        print(f"over tolerance: {r.case} {r.oracle} {r.quantity} {r.worst:.3e} > {r.tolerance:.0e}", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
